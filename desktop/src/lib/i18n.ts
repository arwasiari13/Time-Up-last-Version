const DICTS: Record<Lang, Dict> = { en, ar, fr };

export const LANGUAGES: { key: Lang; label: string }[] = [
  { key: 'en', label: 'English' },
  { key: 'ar', label: 'العربية' },
  { key: 'fr', label: 'Français' },
];

const load = (): Lang => {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === 'ar' || saved === 'fr' || saved === 'en') return saved;
  } catch {
    // التخزين اختياري
  }
  return 'en';
};

let current: Lang = load();

export const getLang = (): Lang => current;

export const isRtl = () => current === 'ar';

/** العربية من اليمين لليسار */
export const applyLangToDocument = () => {
  document.documentElement.lang = current;
  document.documentElement.dir = current === 'ar' ? 'rtl' : 'ltr';
};

export const setLang = (lang: Lang) => {
  current = lang;
  try {
    localStorage.setItem(STORAGE_KEY, lang);
  } catch {
    // التخزين اختياري
  }
  applyLangToDocument();
  // إعادة التحميل أبسط وأضمن من تحديث كل صفحة على حدة
  window.location.reload();
};

/** t('key') أو t('key', { name: 'Ali' }) */
export const t = (key: string, vars?: Record<string, string | number>): string => {
  const text = DICTS[current][key] ?? en[key] ?? key;
  if (!vars) return text;
  return Object.entries(vars).reduce(
    (result, [name, value]) => result.replace(new RegExp(`\\{${name}\\}`, 'g'), String(value)),
    text
  );
};
